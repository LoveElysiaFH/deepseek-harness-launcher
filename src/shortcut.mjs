/** Directory of the installed app bundle (~/Applications/DeepSeek Harness.app). */
export function macAppDir(home = os.homedir()) {
  return path.join(home, 'Applications', `${SHORTCUT_NAME}.app`);
}

/** Generate the Info.plist for the minimal app bundle. */
export function macInfoPlist(version) {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    '<plist version="1.0">',
    '<dict>',
    '  <key>CFBundleName</key>',
    `  <string>${SHORTCUT_NAME}</string>`,
    '  <key>CFBundleDisplayName</key>',
    `  <string>${SHORTCUT_NAME}</string>`,
    '  <key>CFBundleIdentifier</key>',
    `  <string>com.deepseek.harness.launcher</string>`,
    '  <key>CFBundleVersion</key>',
    `  <string>${version}</string>`,
    '  <key>CFBundleShortVersionString</key>',
    `  <string>${version}</string>`,
    '  <key>CFBundleIconFile</key>',
    '  <string>whale-black.icns</string>',
    '  <key>CFBundlePackageType</key>',
    '  <string>APPL</string>',
    '  <key>CFBundleExecutable</key>',
    '  <string>launch</string>',
    '  <key>LSUIElement</key>',
    '  <true/>',
    '</dict>',
    '</plist>',
    '',
  ].join('\n');
}

function shQuote(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

/** Generate the app's executable: run the launcher with the exact node binary. */
export function macLaunchScript(nodeBin, launcherScript) {
  return [
    '#!/bin/sh',
    '# DeepSeek Harness launcher app — generated by "dsh-launcher install".',
    '# Re-run "dsh-launcher install" after moving the launcher folder.',
    `exec ${shQuote(nodeBin)} ${shQuote(launcherScript)} start`,
    '',
  ].join('\n');
}

function readVersion() {
  try {
    return JSON.parse(fs.readFileSync(path.join(launcherRoot(), 'package.json'), 'utf8')).version ?? '1.0.0';
  } catch {
    return '1.0.0';
  }
}

function installMac({ force, t, log }) {
  const root = launcherRoot();
  const iconSource = path.join(root, MAC_ICON);
  if (!fs.existsSync(iconSource)) throw new Error(t('doctor.iconNone'));

  if (!force && shortcutExists()) {
    log(t('shortcut.already', { name: SHORTCUT_NAME }));
    return { installed: false, exists: true };
  }

  log(t('shortcut.installing', { name: SHORTCUT_NAME }));

  // 1. Build the .app bundle in ~/Applications.
  const appDir = macAppDir();
  fs.rmSync(appDir, { recursive: true, force: true });
  const contents = path.join(appDir, 'Contents');
  fs.mkdirSync(path.join(contents, 'MacOS'), { recursive: true });
  fs.mkdirSync(path.join(contents, 'Resources'), { recursive: true });
  fs.writeFileSync(path.join(contents, 'Info.plist'), macInfoPlist(readVersion()), 'utf8');
  fs.copyFileSync(iconSource, path.join(contents, 'Resources', 'whale-black.icns'));
  const execFile = path.join(contents, 'MacOS', 'launch');
  fs.writeFileSync(execFile, macLaunchScript(process.execPath, path.join(root, 'bin', 'launcher.mjs')), 'utf8');
  fs.chmodSync(execFile, 0o755);

  // 2. Link it on the Desktop (symlink; Finder shows the app icon).
  const desktopDir = getDesktopPath();
  let alias = null;
  if (fs.existsSync(desktopDir)) {
    alias = path.join(desktopDir, `${SHORTCUT_NAME}.app`);
    fs.rmSync(alias, { force: true });
    try {
      fs.symlinkSync(appDir, alias, 'dir');
    } catch {
      alias = null; // desktop unavailable (e.g. no GUI); app still installed
    }
  }

  log(t('shortcut.macInstalled', { app: appDir, alias: alias ?? '' }));
  return { installed: true, app: appDir, alias };
}

function uninstallMac({ t, log }) {
  const appDir = macAppDir();
  const alias = path.join(getDesktopPath(), `${SHORTCUT_NAME}.app`);
  const hadApp = fs.existsSync(appDir);
  const hadAlias = fs.existsSync(alias) || fs.lstatSync(alias, { throwIfNoEntry: false })?.isSymbolicLink();
  fs.rmSync(appDir, { recursive: true, force: true });
  fs.rmSync(alias, { force: true });
  if (hadApp || hadAlias) log(t('shortcut.uninstalled', { name: SHORTCUT_NAME }));
  else log(t('shortcut.missing', { name: SHORTCUT_NAME }));
  return { uninstalled: hadApp || hadAlias };
}

// ---------------------------------------------------------------------------
// Entry points
// ---------------------------------------------------------------------------

export function installShortcut({ force = false, t, log = console.log }) {
  if (WINDOWS) return installWindows({ force, t, log });
  if (DARWIN) return installMac({ force, t, log });
  if (process.platform === 'linux') return installLinux({ force, t, log });
  log(t('shortcut.unsupported'));
  return { installed: false, unsupported: true };
}

export function uninstallShortcut({ t, log = console.log }) {
  if (WINDOWS) return uninstallWindows({ t, log });
  if (DARWIN) return uninstallMac({ t, log });
  if (process.platform === 'linux') return uninstallLinux({ t, log });
  log(t('shortcut.unsupported'));
  return { uninstalled: false, unsupported: true };
}
